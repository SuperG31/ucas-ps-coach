#!/usr/bin/env node
/**
 * Generates demo/js/prompts.js and demo/js/personas.js from the canonical sources
 * (prompts/q*.md between BEGIN/END markers, eval/eval-set.json personas).
 * Run after ANY prompt or persona edit:  node tools/build-assets.js
 * This is what keeps the demo and the shipped prompts from drifting (decision D1/D3).
 */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'demo', 'js');

function extractPrompt(qid) {
  const raw = fs.readFileSync(path.join(ROOT, 'prompts', qid + '.md'), 'utf8');
  const m = raw.match(/<!-- BEGIN SYSTEM PROMPT -->\n?([\s\S]*?)<!-- END SYSTEM PROMPT -->/);
  if (!m) throw new Error('No prompt markers in prompts/' + qid + '.md');
  return m[1].trim();
}

const prompts = { q1: extractPrompt('q1'), q2: extractPrompt('q2'), q3: extractPrompt('q3') };

const evalSet = JSON.parse(fs.readFileSync(path.join(ROOT, 'eval', 'eval-set.json'), 'utf8'));
const personas = evalSet.personas.map((p) => ({
  id: p.id,
  name: p.name,
  course: p.course,
  profile: p.profile,
  questions: Object.fromEntries(
    Object.entries(p.questions).map(([qid, q]) => [qid, {
      weakNotes: q.weakNotes,
      weakDraft: q.weakDraft,
      target: q.target,
    }])
  ),
}));

fs.mkdirSync(OUT, { recursive: true });

fs.writeFileSync(path.join(OUT, 'prompts.js'),
  '// GENERATED by tools/build-assets.js from prompts/q*.md — do not edit by hand.\n' +
  'window.PSC = window.PSC || {};\n' +
  'PSC.PROMPTS = ' + JSON.stringify(prompts, null, 2) + ';\n');

fs.writeFileSync(path.join(OUT, 'personas.js'),
  '// GENERATED by tools/build-assets.js from eval/eval-set.json — fictional students only.\n' +
  'window.PSC = window.PSC || {};\n' +
  'PSC.PERSONAS = ' + JSON.stringify(personas, null, 2) + ';\n');

console.log('Wrote demo/js/prompts.js (' + Object.keys(prompts).length + ' prompts) and demo/js/personas.js (' + personas.length + ' personas).');
